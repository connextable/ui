import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import type { PluginOption } from "vite";
import { packageName, readAutoImports, stylesheet } from "./integration";

export interface ConnextableUIViteOptions {
  prefix?: string;
  components?: boolean;
  composables?: boolean;
  css?: boolean;
  dts?: string | false;
}

export default async function connextableUI({
  prefix = "UI",
  components = true,
  composables = true,
  css = true,
  dts = "connextable-ui.d.ts",
}: ConnextableUIViteOptions = {}): Promise<PluginOption[]> {
  const names = components || composables ? await readAutoImports() : { components: [], composables: [] };
  const componentNames = new Map((components ? names.components : []).map(
    name => [`${prefix}${name.slice(2)}`, name] as const,
  ));
  const composableNames = composables ? names.composables : [];

  return [
    {
      name: "connextable-ui",
      configResolved: dts === false ? undefined : async ({ root }) => {
        const output = resolve(root, dts);
        const declarations = ["// Generated by @connextable/ui/vite.", "export {};", ""];
        if (componentNames.size) {
          declarations.push('declare module "vue" {', "  interface GlobalComponents {");
          for (const [alias, name] of componentNames) {
            declarations.push(`    ${JSON.stringify(alias)}: typeof import("${packageName}")["${name}"];`);
          }
          declarations.push("  }", "}", "");
        }
        if (composableNames.length) {
          declarations.push("declare global {");
          for (const name of composableNames) {
            declarations.push(`  const ${name}: typeof import("${packageName}")["${name}"];`);
          }
          declarations.push("}", "");
        }
        const content = declarations.join("\n");
        const current = await readFile(output, "utf8").catch((error: NodeJS.ErrnoException) => {
          if (error.code !== "ENOENT") throw error;
        });
        if (current !== content) {
          await mkdir(dirname(output), { recursive: true });
          await writeFile(output, content, "utf8");
        }
      },
      transformIndexHtml: css ? {
        order: "pre",
        handler: () => [{
          tag: "script",
          attrs: { type: "module" },
          children: `import "${stylesheet}";`,
          injectTo: "head-prepend",
        }],
      } : undefined,
    },
    components && (await import("unplugin-vue-components/vite")).default({
      dirs: [],
      directives: false,
      dts: false,
      resolvers: [(alias) => {
        const name = componentNames.get(alias);
        return name ? { name, from: packageName } : undefined;
      }],
    }),
    composables && (await import("unimport/unplugin")).default.vite({
      imports: composableNames.map(name => ({ name, from: packageName })),
      addons: { vueTemplate: true },
    }),
  ];
}
